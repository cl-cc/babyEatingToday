const ALL_TIPS = WARM_TIPS.concat(NUTRITION_TIPS)

function pickRandomWarmTip(current) {
  if (!ALL_TIPS.length) return ''
  if (ALL_TIPS.length === 1) return ALL_TIPS[0]
  let next = current
  while (next === current) {
    next = ALL_TIPS[Math.floor(Math.random() * ALL_TIPS.length)]
  }
  return next
}

