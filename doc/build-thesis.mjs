function table(headers, rows) {
  const cols = headers.length
  const widths = Array(cols).fill(Math.floor(CONTENT_W / cols))
  widths[widths.length - 1] = CONTENT_W - widths[0] * (cols - 1)
  return new Table({
    width: { size: CONTENT_W, type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({
        children: headers.map((h, i) => cell(h, widths[i], { head: true, align: AlignmentType.CENTER })),
      }),
      ...rows.map(
        (row) =>
          new TableRow({
            children: row.map((c, i) => cell(c, widths[i])),
          }),
      ),
    ],
  })
}

