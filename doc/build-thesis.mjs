function t(text, opt = {}) {
  return new TextRun({
    text,
    font: opt.font || song,
    size: opt.size || 24,
    bold: opt.bold || false,
    italics: opt.italics || false,
  })
}

function p(text, opt = {}) {
  return new Paragraph({
    spacing: opt.spacing || line15,
    alignment: opt.align || AlignmentType.JUSTIFIED,
    indent: opt.indent === false ? undefined : { firstLine: opt.firstLine ?? 480 },
    heading: opt.heading,
    children: [t(text, opt)],
  })
}

function runs(parts, opt = {}) {
  return new Paragraph({
    spacing: opt.spacing || line15,
    alignment: opt.align || AlignmentType.JUSTIFIED,
    indent: opt.indent === false ? undefined : { firstLine: opt.firstLine ?? 480 },
    children: parts.map((part) => (typeof part === 'string' ? t(part, opt) : part)),
  })
}

