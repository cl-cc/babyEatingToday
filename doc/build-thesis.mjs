function countHan(paragraphs) {
  const skip = new Set()
  let n = 0
  const walk = (nodes) => {
    for (const node of nodes) {
      if (!node) continue
      if (node.options && node.options.children) walk(node.options.children)
      if (typeof node === 'object' && node.text) n += (String(node.text).match(/[\u4e00-\u9fff]/g) || []).length
    }
  }
  // fallback: serialize known text by joining later
  return n
}

